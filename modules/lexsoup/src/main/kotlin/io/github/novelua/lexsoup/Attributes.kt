package io.github.novelua.lexsoup
/**
 * Represents Attributes.
 */
class Attributes {
    /**
     * Executes get.
     */
    fun get(key: String): String = ""
    /**
     * Executes put.
     */
    fun put(key: String, value: String) {}
    /**
     * Executes remove.
     */
    fun remove(key: String) {}
    /**
     * Executes hasKey.
     */
    fun hasKey(key: String): Boolean = false
}
